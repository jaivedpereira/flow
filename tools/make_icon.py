#!/usr/bin/env python3
"""
Turn the chosen icon (D4-final, isometric LUT cube) into real Android assets.

Produces:
  - drawable/ic_launcher_foreground.xml   vector, exact at any density
  - drawable/ic_launcher_monochrome.xml   themed-icon silhouette (Android 13+)
  - mipmap-*/ic_launcher.png              legacy PNGs for API < 26
  - mipmap-*/ic_launcher_round.png        legacy round PNGs
  - values/ic_launcher_background.xml     background colour

Geometry note: the adaptive-icon safe zone is a 66dp circle inside the 108dp
canvas. The cube is sized so its full width fits inside 72dp, which keeps it
uncropped under circle, squircle AND rounded-square masks.
"""
import os
import math
from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.abspath(os.path.join(HERE, "..", "app", "src", "main", "res"))

# ---- canvas / geometry
VP = 108.0                 # viewport in dp
CX, CY = 54.0, 54.0        # cube centre
S = 18.0                   # half-edge -> height 4S = 72dp, width 3.464S ≈ 62.3dp
K = 0.8660254              # cos(30deg)

# D2-dusk: a violet-to-ember gradient on the top face. It reads as a sunset
# grade, which is what the app is for, rather than as a neutral object.
COLOURS = {
    "bg":      (6, 5, 10),
    "top":     [(247, 226, 206), (240, 178, 150), (214, 122, 104),
                (150, 82, 104), (86, 58, 108)],
    "left":    (24, 18, 34),
    "right":   (46, 28, 32),
    "edge":    (120, 96, 96),
}


def iso(x, y, z):
    """Isometric projection from cube space (-1..1) to viewport dp."""
    px = CX + (x - z) * S * K
    py = CY + (x + z) * S * 0.5 - y * S
    return (round(px, 3), round(py, 3))


def hexc(rgb, alpha=1.0):
    r, g, b = rgb
    if alpha >= 1.0:
        return f"#{r:02X}{g:02X}{b:02X}"
    a = int(round(alpha * 255))
    return f"#{a:02X}{r:02X}{g:02X}{b:02X}"


def path_of(points, close=True):
    d = f"M{points[0][0]},{points[0][1]}"
    for p in points[1:]:
        d += f" L{p[0]},{p[1]}"
    if close:
        d += " Z"
    return d


# ---- faces
# Visible faces in this projection:
#   TOP   = y = +1
#   LEFT  = z = +1   (faces the viewer's left)
#   RIGHT = x = +1   (faces the viewer's right)
TOP = [iso(1, 1, 1), iso(-1, 1, 1), iso(-1, 1, -1), iso(1, 1, -1)]
LEFT = [iso(1, 1, 1), iso(1, -1, 1), iso(-1, -1, 1), iso(-1, 1, 1)]
RIGHT = [iso(1, 1, 1), iso(1, -1, 1), iso(1, -1, -1), iso(1, 1, -1)]


def top_band(i, n):
    t0 = i / n
    t1 = (i + 1) / n
    return [
        iso(1, 1, 1 - 2 * t0),
        iso(-1, 1, 1 - 2 * t0),
        iso(-1, 1, 1 - 2 * t1),
        iso(1, 1, 1 - 2 * t1),
    ]


def build_foreground():
    n = len(COLOURS["top"])
    parts = [
        '<?xml version="1.0" encoding="utf-8"?>',
        '<!-- Generated by tools/make_icon.py: isometric LUT cube -->',
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{VP:g}dp"',
        f'    android:height="{VP:g}dp"',
        f'    android:viewportWidth="{VP:g}"',
        f'    android:viewportHeight="{VP:g}">',
        '',
        f'    <!-- left face -->',
        f'    <path android:fillColor="{hexc(COLOURS["left"])}" android:pathData="{path_of(LEFT)}"/>',
        f'    <!-- right face -->',
        f'    <path android:fillColor="{hexc(COLOURS["right"])}" android:pathData="{path_of(RIGHT)}"/>',
        '',
        '    <!-- LUT gradient bands on the top face -->',
    ]
    for i in range(n):
        pts = top_band(i, n)
        parts.append(
            f'    <path android:fillColor="{hexc(COLOURS["top"][i])}" android:pathData="{path_of(pts)}"/>'
        )

    # crisp edges
    e = COLOURS["edge"]
    sw = 1.15
    parts += [
        '',
        '    <!-- edges -->',
    ]
    for face in (TOP, LEFT, RIGHT):
        parts.append(
            f'    <path android:strokeColor="{hexc(e)}" android:strokeWidth="{sw:g}" '
            f'android:strokeLineJoin="round" android:fillColor="#00000000" '
            f'android:pathData="{path_of(face)}"/>'
        )
    parts.append('</vector>')
    return "\n".join(parts) + "\n"


def build_monochrome():
    """Android 13 themed icons: single-colour silhouette."""
    parts = [
        '<?xml version="1.0" encoding="utf-8"?>',
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{VP:g}dp"',
        f'    android:height="{VP:g}dp"',
        f'    android:viewportWidth="{VP:g}"',
        f'    android:viewportHeight="{VP:g}">',
        '    <path android:fillColor="#FFFFFFFF" android:pathData="' + path_of(TOP) + '"/>',
        '    <path android:fillColor="#FFFFFFFF" android:pathData="' + path_of(LEFT) + '"/>',
        '    <path android:fillColor="#FFFFFFFF" android:pathData="' + path_of(RIGHT) + '"/>',
        '</vector>',
    ]
    return "\n".join(parts) + "\n"


# ---- raster previews for legacy mipmaps
DENSITIES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}


def render_raster(size, round_mask=False, ss=4):
    big = size * ss
    bg_rgb = COLOURS["bg"]
    img = Image.new("RGBA", (big, big), bg_rgb + (255,))
    d = ImageDraw.Draw(img)
    sc = big / VP

    def P(pts):
        return [(x * sc, y * sc) for x, y in pts]

    d.polygon(P(LEFT), fill=COLOURS["left"] + (255,))
    d.polygon(P(RIGHT), fill=COLOURS["right"] + (255,))
    n = len(COLOURS["top"])
    for i in range(n):
        d.polygon(P(top_band(i, n)), fill=COLOURS["top"][i] + (255,))

    ew = max(1, int(1.15 * sc))
    for face in (TOP, LEFT, RIGHT):
        pts = P(face) + [P(face)[0]]
        d.line(pts, fill=COLOURS["edge"] + (255,), width=ew, joint="curve")

    img = img.resize((size, size), Image.LANCZOS)

    if round_mask:
        mask = Image.new("L", (size, size), 0)
        ImageDraw.Draw(mask).ellipse([0, 0, size - 1, size - 1], fill=255)
        out = Image.new("RGBA", (size, size), (0, 0, 0, 0))
        out.paste(img, (0, 0), mask)
        img = out

    return img


def main():
    print(f"geometry: S={S} -> width {3.464 * S:.1f}dp (safe zone 66dp, fits 72dp)")
    print(f"  top    {[ (round(x,1),round(y,1)) for x,y in TOP ]}")
    print(f"  left   {[ (round(x,1),round(y,1)) for x,y in LEFT ]}")
    print(f"  right  {[ (round(x,1),round(y,1)) for x,y in RIGHT ]}")

    # bounds check
    allp = TOP + LEFT + RIGHT
    xs = [p[0] for p in allp]
    ys = [p[1] for p in allp]
    w, h = max(xs) - min(xs), max(ys) - min(ys)
    print(f"  actual bounds: {w:.1f} x {h:.1f} dp  (x {min(xs):.1f}..{max(xs):.1f}, y {min(ys):.1f}..{max(ys):.1f})")
    cx_canvas = 54
    max_r = max(math.hypot(p[0] - cx_canvas, p[1] - 54) for p in allp)
    print(f"  max radius from centre: {max_r:.1f}dp  (safe circle radius 33dp)")

    # write vector drawables
    drawable = os.path.join(RES, "drawable")
    os.makedirs(drawable, exist_ok=True)
    with open(os.path.join(drawable, "ic_launcher_foreground.xml"), "w", encoding="utf-8") as f:
        f.write(build_foreground())
    print("  drawable/ic_launcher_foreground.xml")

    with open(os.path.join(drawable, "ic_launcher_monochrome.xml"), "w", encoding="utf-8") as f:
        f.write(build_monochrome())
    print("  drawable/ic_launcher_monochrome.xml")

    # legacy raster mipmaps
    for name, px in DENSITIES.items():
        folder = os.path.join(RES, f"mipmap-{name}")
        os.makedirs(folder, exist_ok=True)
        render_raster(px).save(os.path.join(folder, "ic_launcher.png"), optimize=True)
        render_raster(px, round_mask=True).save(
            os.path.join(folder, "ic_launcher_round.png"), optimize=True
        )
        print(f"  mipmap-{name}/  {px}px")

    # background colour
    values = os.path.join(RES, "values")
    os.makedirs(values, exist_ok=True)
    with open(os.path.join(values, "ic_launcher_background.xml"), "w", encoding="utf-8") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
                '    <color name="ic_launcher_background">#FF06050A</color>\n</resources>\n')
    print("  values/ic_launcher_background.xml")

    # adaptive icon xml (with monochrome for themed icons)
    anydpi = os.path.join(RES, "mipmap-anydpi-v26")
    os.makedirs(anydpi, exist_ok=True)
    adaptive = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/ic_launcher_background" />\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
        '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
        '</adaptive-icon>\n'
    )
    for fn in ("ic_launcher.xml", "ic_launcher_round.xml"):
        with open(os.path.join(anydpi, fn), "w", encoding="utf-8") as f:
            f.write(adaptive)
        print(f"  mipmap-anydpi-v26/{fn}")


if __name__ == "__main__":
    main()
